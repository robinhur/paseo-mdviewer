// Prepares generated server modules. The daemon bundles plugin server code itself and rejects
// packages whose type declarations it cannot follow, so the Markdown engine and the browser
// runtimes are pre-built here into plain modules with local declarations. It also writes
// THIRD_PARTY_NOTICES.md for every package that ends up in those modules.
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const result = await build({
  entryPoints: ["engine/render.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: "server/generated/engine.js",
  legalComments: "none",
  logLevel: "warning",
  metafile: true,
});
writeFileSync(
  "server/generated/engine.d.ts",
  `// Generated by scripts/build.mjs. Do not edit.
export interface Heading { level: number; text: string; id: string; line: number }
export interface RenderResult { html: string; title: string; headings: Heading[] }
export declare function renderMarkdown(text: string, docPath?: string): RenderResult;
export declare function slugify(text: string): string;
`,
);
execFileSync(process.execPath, ["scripts/gen-runtime.mjs"], { stdio: "inherit" });

// Packages bundled into the engine, plus the browser runtimes embedded as text.
const bundled = new Set(["mermaid", "katex", "dompurify"]);
for (const input of Object.keys(result.metafile.inputs)) {
  const match = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (match) bundled.add(match[1]);
}

function licenseText(dir) {
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name));
  return file ? readFileSync(path.join(dir, file), "utf8").replace(/[ \t]+$/gm, "").trim() : "";
}

const sections = [...bundled].sort().map((name) => {
  const dir = path.join("node_modules", name);
  if (!existsSync(dir)) return `## ${name}\n\nNot installed when these notices were generated.`;
  const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "see text";
  const text = licenseText(dir);
  return `## ${name} ${pkg.version}\n\nLicense: ${license}\n\n${text ? "```\n" + text + "\n```" : "No license file in the package."}`;
});

writeFileSync(
  "THIRD_PARTY_NOTICES.md",
  `# Third-party notices\n\nMDViewer ships the following packages inside \`server/generated/\`. Generated by \`npm run build\`.\n\n` +
    "Mermaid's browser build also bundles its own dependencies under their licenses; see the mermaid package for details.\n\n" +
    sections.join("\n\n") +
    "\n",
);
console.log(`engine built; ${bundled.size} packages listed in THIRD_PARTY_NOTICES.md`);
